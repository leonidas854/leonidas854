"""Compose static HTML and GitHub READMEs from editable components. No dependencies."""
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parent.parent
SRC=ROOT/'src'


def compose(path):
    def include(match):
        child=(path.parent/match[1]).resolve()
        if not child.is_relative_to(SRC):
            raise ValueError(f'Include outside src: {child}')
        return compose(child).rstrip()
    return re.sub(r'<!-- include: (.*?) -->',include,path.read_text())


(ROOT/'index.html').write_text('<!-- Generated by scripts/build.py; edit src/page.html and its components. -->\n'+compose(SRC/'page.html'))
for language,name in [('es','README.md'),('en','README.en.md')]:
    entry=SRC/'readme'/language/'index.md'
    if entry.exists():
        (ROOT/name).write_text('<!-- Generated by scripts/build.py; edit src/readme/'+language+'/. -->\n'+compose(entry))
print('Built index.html and README components')
